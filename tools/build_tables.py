"""Generate the tables that come from data files, so the docs cannot drift from the data.
  docs/COMMUNITY-RESULTS.md      from data/community/*.json (validated against data/community/schema.json when jsonschema is installed)
  docs/PEERS.md  (marked block)  from data/peer-benchmarks.csv
Usage: python tools/build_tables.py            (no third-party packages needed; jsonschema is used if present)
       python tools/build_tables.py --check    exit 1 if a generated file is out of date (used by CI)"""
import csv, glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = "https://github.com/edagher92-coder/arc-llm-lab"
ISSUE = REPO + "/issues/new?template=benchmark.yml"

def community():
    recs = []
    for p in sorted(glob.glob(os.path.join(ROOT, "data", "community", "*.json"))):
        if os.path.basename(p) == "schema.json": continue
        d = json.load(open(p, encoding="utf-8")); d["_file"] = os.path.basename(p); recs.append(d)
    try:
        import jsonschema
        schema = json.load(open(os.path.join(ROOT, "data", "community", "schema.json"), encoding="utf-8"))
        for d in recs: jsonschema.validate({k: v for k, v in d.items() if k != "_file"}, schema)
    except ImportError:
        pass
    return sorted(recs, key=lambda d: (d["gpu"], d["llama_cpp_build"], d["date"]))

def depth_label(d):
    n = int(d); return "empty" if n == 0 else ("%dK" % (n // 1024) if n % 1024 == 0 else str(n))

def community_md(recs):
    L = ["# Community results", "",
         "<!-- Generated by tools/build_tables.py from data/community/*.json. Do not edit by hand: add a JSON file instead. -->", "",
         "Numbers from real Intel GPUs, measured with `llama-bench` using one command: [bench/arc-bench.ps1](../bench/arc-bench.ps1) (Windows) or [bench/arc-bench.sh](../bench/arc-bench.sh) (Linux). Each result is a small JSON file in [data/community/](../data/community/) that follows [schema.json](../data/community/schema.json).", "",
         "**Add your card:** run the script, then [open a benchmark issue](%s) and paste the JSON, or send a pull request that adds it to `data/community/`. The raw `llama-bench` output is required, because a number without a log can't be checked. See [GOOD-FIRST-ISSUES.md](GOOD-FIRST-ISSUES.md) for cards and setups we most want to see." % ISSUE, "",
         "All figures are tokens per second from `llama-bench` (`pp` is prompt processing, `tg` is token generation), at the context depths shown. They measure the engine without speculative decoding, so they are directly comparable between cards. Results are self-reported unless the notes say otherwise.", ""]
    if not recs:
        L += ["_No results yet._", ""]; return "\n".join(L) + "\n"
    L += ["| GPU | VRAM | Backend / build | Patches | Model | Depths | pp (tok/s) | tg (tok/s) | Driver / OS | By | Raw |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in recs:
        ds = sorted(d["depth_results"], key=int)
        pp = " / ".join("%.2f" % d["depth_results"][k]["pp_tok_s"] for k in ds); tg = " / ".join("%.2f" % d["depth_results"][k]["tg_tok_s"] for k in ds)
        n = d["depth_results"][ds[0]]
        patches = "%d (%s)" % (len(d["patches"]), ", ".join(p[:9] for p in d["patches"])) if d["patches"] else "none"
        raw = "[log](%s)" % d["raw_log_url"] if d.get("raw_log_url") else "-"
        L.append("| %s | %s GB | %s %s | %s | %s (%s, KV %s/%s) | %s | %s | %s | %s, %s | %s | %s |" % (
            d["gpu"], ("%g" % d["vram_gb"]), d["backend"], d["llama_cpp_build"], patches, d["model"], d["quant"], d["kv_cache"]["k"], d["kv_cache"]["v"],
            " / ".join(depth_label(k) for k in ds), pp, tg, d["driver"], d["os"], d["contributor"], raw))
    L += ["", "pp is prompt processing of a %d-token prompt and tg is generation of %d tokens, both at the stated depth." % (n.get("pp_tokens", 2048), n.get("tg_tokens", 32)), "", "## Notes", ""]
    for d in recs:
        if d.get("notes"): L.append("- **%s, %s %s (%s):** %s" % (d["gpu"], d["backend"], d["llama_cpp_build"], d["date"], d["notes"]))
    L += ["", "How these compare with other people's B60 numbers: [PEERS.md](PEERS.md)."]
    return "\n".join(L) + "\n"

def peers_table():
    rows = list(csv.DictReader(open(os.path.join(ROOT, "data", "peer-benchmarks.csv"), encoding="utf-8")))
    L = ["| Source | Date | GPU | Model, quant | Backend | Spec. decoding | Depth (tokens) | pp tok/s | tg tok/s | Notes |", "|---|---|---|---|---|---|---|---|---|---|"]
    esc = lambda s: (s or "").replace("|", "/").replace("\n", " ")
    for r in rows:
        src = "[%s](%s)" % (esc(r["source"]), r["url"]) if r["url"] else esc(r["source"])
        L.append("| %s | %s | %s | %s, %s | %s | %s | %s | %s | %s | %s |" % (src, r["date"] or "n/d", esc(r["gpu"]) + (" x%s" % r["gpu_count"] if r["gpu_count"] not in ("", "1") else ""),
                 esc(r["model"]), esc(r["quant"]), esc(r["backend"]), esc(r["spec_decode"]) or "-", esc(r["ctx_depth_tokens"]) or "n/d", esc(r["pp_tok_s"]) or "-", esc(r["tg_tok_s"]) or "-", esc(r["notes"])))
    return "\n".join(L)

def replace_block(text, name, body):
    a, b = "<!-- %s:start -->" % name, "<!-- %s:end -->" % name
    i, j = text.index(a) + len(a), text.index(b)
    return text[:i] + "\n" + body + "\n" + text[j:]

def main():
    check = "--check" in sys.argv; bad = 0
    out = {os.path.join(ROOT, "docs", "COMMUNITY-RESULTS.md"): community_md(community())}
    pp = os.path.join(ROOT, "docs", "PEERS.md")
    if os.path.exists(pp): out[pp] = replace_block(open(pp, encoding="utf-8").read(), "peers-table", peers_table())
    for path, text in out.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if check:
            if old != text: print("OUT OF DATE:", os.path.relpath(path, ROOT)); bad += 1
        elif old != text:
            open(path, "w", encoding="utf-8", newline="\n").write(text); print("wrote", os.path.relpath(path, ROOT))
    sys.exit(1 if bad else 0)

if __name__ == "__main__":
    main()
